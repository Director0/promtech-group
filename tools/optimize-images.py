"""Make light web copies of the site's heavy images.

The original renders stay untouched (they can be 40+ MB, 5760 px wide). For
every image in the folders below this script writes resized WebP copies into
assets/opt/ and a map assets/js/images.js that the pages use to swap in the
light copy automatically:

    card  — max 960 px wide   (project cards, news cards, card → page morph)
    hero  — max 2048 px wide  (project hero, gallery, about photo, news modal)

Run again after adding or replacing images:

    py tools/optimize-images.py

Needs Pillow (py -m pip install --user pillow).
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["assets/projects", "assets/models", "assets/licenses", "assets/achievements", "assets/specs"]
OUT = ROOT / "assets" / "opt"
SIZES = {"card": (960, 80), "hero": (2048, 82)}            # name: (max width, WebP quality)
EXTS = {".png", ".jpg", ".jpeg", ".webp"}

Image.MAX_IMAGE_PIXELS = None                              # the renders are big on purpose


def main():
    mapping = {}
    for folder in SOURCES:
        base = ROOT / folder
        if not base.exists():
            continue
        for src in sorted(base.rglob("*")):
            if src.suffix.lower() not in EXTS or not src.is_file():
                continue
            rel = src.relative_to(ROOT).as_posix()
            entry = {}
            with Image.open(src) as im:
                im = im.convert("RGBA") if im.mode in ("P", "LA", "RGBA") else im.convert("RGB")
                for name, (max_w, q) in SIZES.items():
                    dst = OUT / Path(rel).relative_to("assets").with_suffix("") .with_name(
                        f"{src.stem}-{name}.webp")
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    fresh = not dst.exists() or dst.stat().st_mtime < src.stat().st_mtime
                    if fresh:
                        w, h = im.size
                        copy = im if w <= max_w else im.resize((max_w, round(h * max_w / w)), Image.LANCZOS)
                        copy.save(dst, "WEBP", quality=q, method=6)
                    entry[name] = dst.relative_to(ROOT).as_posix()
            mapping[rel] = entry
            sizes = ", ".join(f"{k} {(ROOT / v).stat().st_size / 1024:.0f} KB" for k, v in entry.items())
            print(f"{src.stat().st_size / 1048576:6.1f} MB  {rel}  ->  {sizes}")

    helper = r'''
/* optImg(src, "card" | "hero") -> the light copy, or src itself when there is none */
window.optImg = function (src, size) {
  if (!src) return src;
  var e = window.IMG_OPT[String(src).replace(/^\.\//, "")];
  return (e && e[size || "hero"]) || src;
};
'''
    js = ("/* generated by tools/optimize-images.py — do not edit by hand.\n"
          "   original image path → light WebP copies (card / hero). */\n"
          "window.IMG_OPT = " + json.dumps(mapping, ensure_ascii=False, indent=1) + ";\n" + helper)
    (ROOT / "assets" / "js" / "images.js").write_text(js, encoding="utf-8")
    print(f"\n{len(mapping)} images -> assets/js/images.js")


if __name__ == "__main__":
    main()
